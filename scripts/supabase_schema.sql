-- 1. TABEL UTAMA: knowledge_base (~2.229 record)
CREATE TABLE IF NOT EXISTS public.knowledge_base (
    id TEXT PRIMARY KEY,
    category TEXT,
    title TEXT NOT NULL,
    answer TEXT NOT NULL,
    keywords TEXT[] DEFAULT '{}',
    aliases TEXT[] DEFAULT '{}',
    entity TEXT,
    source_ref TEXT,
    agencies TEXT[] DEFAULT '{}',
    agency_level TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_kb_active ON public.knowledge_base (is_active);
CREATE INDEX IF NOT EXISTS idx_kb_category ON public.knowledge_base (category);

-- 2. TABEL RIWAYAT CHAT: chat_logs
CREATE TABLE IF NOT EXISTS public.chat_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_query TEXT NOT NULL,
    normalized_query TEXT,
    matched_kb JSONB DEFAULT '[]'::jsonb,
    ai_response TEXT NOT NULL,
    has_answer BOOLEAN DEFAULT FALSE,
    response_time_ms INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABEL PENGUJIAN & AKURASI: test_evaluations
CREATE TABLE IF NOT EXISTS public.test_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_question TEXT NOT NULL,
    expected_topic TEXT,
    normalized_query TEXT,
    top_kb_results JSONB DEFAULT '[]'::jsonb,
    ai_answer TEXT,
    has_answer BOOLEAN DEFAULT FALSE,
    is_accurate BOOLEAN DEFAULT NULL,
    notes TEXT,
    tested_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. FUNGSI PENCARIAN & RELEVANCE SCORING: search_kb_relevance
CREATE OR REPLACE FUNCTION public.search_kb_relevance(
    p_normalized_query TEXT,
    p_tokens TEXT[],
    p_limit INTEGER DEFAULT 5
)
RETURNS TABLE (
    id TEXT,
    category TEXT,
    title TEXT,
    answer TEXT,
    keywords TEXT[],
    source_ref TEXT,
    relevance_score NUMERIC
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    WITH scored AS (
        SELECT
            kb.id,
            kb.category,
            kb.title,
            kb.answer,
            kb.keywords,
            kb.source_ref,
            (
                CASE WHEN p_normalized_query <> '' AND lower(kb.title) LIKE '%' || p_normalized_query || '%' THEN 15.0 ELSE 0.0 END
                +
                CASE WHEN p_normalized_query <> '' AND EXISTS (
                    SELECT 1 FROM unnest(kb.keywords) kw WHERE lower(kw) LIKE '%' || p_normalized_query || '%'
                ) THEN 15.0 ELSE 0.0 END
                +
                COALESCE((
                    SELECT SUM(
                        (CASE WHEN lower(kb.title) LIKE '%' || token || '%' THEN 4.0 ELSE 0.0 END) +
                        (CASE WHEN EXISTS (SELECT 1 FROM unnest(kb.keywords) kw WHERE lower(kw) LIKE '%' || token || '%') THEN 3.0 ELSE 0.0 END) +
                        (CASE WHEN lower(COALESCE(kb.category, '')) LIKE '%' || token || '%' THEN 2.0 ELSE 0.0 END) +
                        (CASE WHEN lower(kb.answer) LIKE '%' || token || '%' THEN 1.0 ELSE 0.0 END)
                    )
                    FROM unnest(p_tokens) AS token
                    WHERE length(token) >= 2
                ), 0.0)
            )::NUMERIC AS score
        FROM public.knowledge_base kb
        WHERE kb.is_active = TRUE
    )
    SELECT
        s.id,
        s.category,
        s.title,
        s.answer,
        s.keywords,
        s.source_ref,
        s.score AS relevance_score
    FROM scored s
    WHERE s.score > 0
    ORDER BY s.score DESC, s.title ASC
    LIMIT p_limit;
END;
$$;

-- 5. IZIN AKSES & NONAKTIFKAN RLS UNTUK KEMUDAHAN POC
ALTER TABLE public.knowledge_base DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_logs DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.test_evaluations DISABLE ROW LEVEL SECURITY;

GRANT ALL ON TABLE public.knowledge_base TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.chat_logs TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.test_evaluations TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
